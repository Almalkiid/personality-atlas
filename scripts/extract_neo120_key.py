"""Extract the IPIP-NEO-120 items and key from Johnson's official IPIP-NEO-ItemKey.xls
(OSF https://osf.io/download/yk3fd/) into js/instruments/ipipneo120.js.

Run from the repo root:  python3 -P scripts/extract_neo120_key.py raw/IPIP-NEO-ItemKey.xls
"""
import json
import sys

import xlrd

DOMAIN_NAMES = {"N": "Neuroticism", "E": "Extraversion", "O": "Openness to Experience",
                "A": "Agreeableness", "C": "Conscientiousness"}


def main(path):
    sheet = xlrd.open_workbook(path).sheet_by_index(0)
    header = sheet.row_values(0)
    assert header == ["Full#", "Short#", "Sign", "Key", "Facet", "Item"], header
    rows = []
    facet_names = {}
    for r in range(1, sheet.nrows):
        full, short, sign, key, facet_name, text = sheet.row_values(r)
        if short in ("", None):
            continue
        sign = sign.strip()
        assert sign[0] in "+-" and sign[1:] == key, (r, sign, key)
        domain, facet = key[0], int(key[1:])
        facet_names.setdefault((domain, facet), facet_name.strip())
        assert facet_names[(domain, facet)] == facet_name.strip(), (r, facet_name)
        rows.append((int(short), {
            "text": text.strip(), "domain": domain, "facet": facet,
            "keyed": "plus" if sign[0] == "+" else "minus",
        }))
    rows.sort(key=lambda x: x[0])
    shorts = [s for s, _ in rows]
    assert shorts == list(range(1, 121)), f"short numbers not 1..120: {len(shorts)}"
    items = [dict(id=f"i{s}", **it) for s, it in rows]
    facets = [{"domain": d, "facet": f, "name": n} for (d, f), n in sorted(facet_names.items(), key=lambda x: ("NEOAC".index(x[0][0]), x[0][1]))]
    domains = [{"id": d, "name": DOMAIN_NAMES[d]} for d in "NEOAC"]
    body = (
        "// IPIP-NEO-120 (Johnson, 2014, J. Research in Personality 51, 78–89), public domain.\n"
        "// GENERATED by scripts/extract_neo120_key.py from Johnson's official IPIP-NEO-ItemKey.xls\n"
        "// (OSF https://osf.io/download/yk3fd/). Item order = Johnson's short-form numbering = IPIP120.dat I1..I120.\n"
        "export const ipipneo120 = {\n"
        '  id: "ipipneo120",\n  name: "In-depth",\n  fullName: "IPIP-NEO-120 (120 items, 30 facets)",\n  minutes: 15,\n'
        f"  domains: {json.dumps(domains)},\n"
        f"  facets: {json.dumps(facets, indent=2)},\n"
        f"  items: {json.dumps(items, indent=2)}\n"
        "};\n"
    )
    with open("js/instruments/ipipneo120.js", "w") as fh:
        fh.write(body)
    print(f"items={len(items)} facets={len(facets)}")


if __name__ == "__main__":
    main(sys.argv[1])
